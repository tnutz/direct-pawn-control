local out = {}
local pm = sdk.get_managed_singleton("app.PawnManager")
local lst = pm:call("get_PawnCharacterList")
local ch = lst:call("get_Item", 1)
local hit = ch:call("get_Hit")
out[#out+1] = "before: " .. tostring(ch:call("get_CharaIDString")) .. " hp " .. tostring(ch:call("get_Hp")) .. " dead " .. tostring(ch:call("get_IsDead"))
local ok, err = pcall(function()
  local di = sdk.create_instance("app.HitController.DamageInfo")
  if not di then error("no DamageInfo instance") end
  di = di:add_ref()
  di:set_field("Damage", 99999.0)
  di:set_field("FixedDamage", 99999.0)
  di:set_field("IsDirectDamage", true)
  di:set_field("<DamageHitController>k__BackingField", hit)
  di:set_field("<DamageOwnerHitController>k__BackingField", hit)
  hit:call("updateDamageHp(app.HitController.DamageInfo, System.Single, System.Boolean)", di, 99999.0, false)
end)
out[#out+1] = "call ok=" .. tostring(ok) .. " " .. tostring(err)
out[#out+1] = "after: hp " .. tostring(ch:call("get_Hp")) .. " dead " .. tostring(ch:call("get_IsDead")) .. " isDie " .. tostring(hit:call("get_IsDie")) .. " startDead " .. tostring(hit:call("get_IsStartDead"))
return table.concat(out, "\n")
